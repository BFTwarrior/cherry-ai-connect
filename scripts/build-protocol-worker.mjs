import { spawnSync } from 'node:child_process';
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
const root=path.resolve(import.meta.dirname,'..');
const localGo='H:\\AI\\Go工具链\\go\\bin\\go.exe';
const go=process.env.GO_BINARY || (fs.existsSync(localGo)?localGo:'go');
const version=spawnSync(go,['version'],{encoding:'utf8',windowsHide:true});
if(version.status!==0 || !version.stdout.includes('go1.27.4')) throw new Error('translator_requires_go1.27.4');
const output=path.join(root,'electron','assets','cherry-translator.exe');
const result=spawnSync(go,['build','-trimpath','-tags=nomsgpack','-ldflags=-s -w','-o',output,'./cmd/cherry-translator'],{cwd:path.join(root,'protocol-worker'),stdio:'inherit',windowsHide:true,env:{...process.env,GOOS:'windows',GOARCH:'amd64',CGO_ENABLED:'0',GOTOOLCHAIN:'local'}});
if(result.status!==0) throw new Error('translator_build_failed');
const hash=crypto.createHash('sha256').update(fs.readFileSync(output)).digest('hex');
fs.writeFileSync(`${output}.json`,JSON.stringify({version:'cherry-translator-1',sha256:hash}));
const notices=[fs.readFileSync(path.join(root,'protocol-worker','LICENSE'),'utf8')];
const visit=directory=>{for(const entry of fs.readdirSync(directory,{withFileTypes:true})){const file=path.join(directory,entry.name);if(entry.isDirectory())visit(file);else notices.push(`\n--- ${path.relative(path.join(root,'protocol-worker','licenses'),file)} ---\n${fs.readFileSync(file,'utf8')}`);}};
visit(path.join(root,'protocol-worker','licenses'));
fs.writeFileSync(path.join(root,'electron','assets','translator-NOTICES.txt'),notices.join('\n'));
console.log(`Translator built: ${fs.statSync(output).size} bytes; SHA-256 ${hash}`);
